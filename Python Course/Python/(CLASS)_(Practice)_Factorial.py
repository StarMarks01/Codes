class classa:
    def inputs(self):
        self.factorial=int(input("Enter Value In Factorial:-"))
    def factorials(s):
        if s.factorial<=0:
            print("sorry the factorial cannot be less than or zero")
        else:
            for i in range(1,s.factorial):
                s.factorial = s.factorial*i
            print(s.factorial)
ca=classa()
ca.inputs()
ca.factorials()
