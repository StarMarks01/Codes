from turtle import *
t = Turtle()
t.pensize(4)
t.speed(1)
t.up()
t.goto(-80,0)
t.down()
t.fillcolor("green")
t.begin_fill()
t.rt(90)
t.fd(100)
t.lt(90)
t.fd(350)
t.lt(90)
t.fd(100)
t.lt(90)
t.fd(350)
t.end_fill()
t.up()
t.goto(-80,100)
t.down()
t.rt(180)
t.fd(350)
t.rt(90)
t.fd(100)
t.rt(90)
t.fd(350)
t.rt(90)
t.fd(100)
t.color("orange")
t.begin_fill()
t.fd(100)
t.rt(90)
t.fd(350)
t.rt(90)
t.fd(100)
t.rt(90)
t.fd(350)
t.end_fill()
t.up()
t.goto(100,90)
t.color("navy")
t.begin_fill()
t.circle(40)
t.end_fill()
t.up()
t.goto(90,90)
t.down()
t.color("white")
t.begin_fill()
t.circle(34)
t.end_fill()
exitonclick()
