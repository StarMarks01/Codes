from turtle import * 
title("RAPGOD")
t = Turtle()
t.speed(1)
t.pensize(2)
t.color("Green")
t.begin_fill()
t.fd(200)
t.rt(90)
t.fd(200)
t.rt(90)
t.fd(200)
t.rt(90)
t.fd(200)
t.end_fill()
t.penup()
t.goto(0,40)
t.pendown()
t.pensize(3)
t.color("navy")
t.begin_fill()
t.rt(90)
t.fd(300)
t.lt(90)
t.fd(150)
t.lt(90)
t.fd(300)
t.lt(90)
t.fd(150)
t.end_fill()
t.up()
t.goto(-300,89)
t.down()
t.color("purple")
t.begin_fill()
t.circle(150)
t.end_fill()
exitonclick()
